CREATE TABLE users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    pwd TEXT NOT NULL,
    is_admin BOOL NOT NULL DEFAULT false
);

CREATE TABLE sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id INT NOT NULL REFERENCES users(id),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE households (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    code VARCHAR(6) CHECK (char_length(code) = 6) NOT NULL UNIQUE,
    version INT NOT NULL DEFAULT 0,
    created_by INT NOT NULL REFERENCES users(id)
);

CREATE TYPE household_role AS ENUM ('owner', 'member');

CREATE TABLE household_members (
    user_id INT NOT NULL REFERENCES users(id),
    household_id INT NOT NULL REFERENCES households(id),
    role household_role NOT NULL DEFAULT 'member',
    PRIMARY KEY (user_id, household_id)
);

CREATE TABLE invites (
    token UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    household_id INT NOT NULL REFERENCES households(id) ON DELETE CASCADE,
    created_by INT NOT NULL REFERENCES users(id),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE products (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    brand TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL,
    
    CONSTRAINT unique_product
    UNIQUE (name, brand)
);

CREATE TABLE grocery_lists (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT '',
    household_id INT NOT NULL REFERENCES households(id)
);

CREATE TABLE groceries (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grocery_list_id INT NOT NULL REFERENCES grocery_lists(id) ON DELETE CASCADE,
    product_id INT NOT NULL REFERENCES products(id),
    amount TEXT NOT NULL DEFAULT '',
    picked BOOL NOT NULL DEFAULT FALSE
);

CREATE TABLE groceries_history (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id INT NOT NULL REFERENCES households(id),
    product_id int NOT NULL REFERENCES products(id),
    times_added INT NOT NULL DEFAULT 1,
    CONSTRAINT unique_household_product_history UNIQUE (household_id, product_id)
);

CREATE TABLE household_product_category (
    household_id INT NOT NULL REFERENCES households(id),
    product_id   INT NOT NULL REFERENCES products(id),
    category     TEXT NOT NULL,
    PRIMARY KEY (household_id, product_id)
);

CREATE TABLE recipes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    img_url TEXT,
    link TEXT,
    household_id INT NOT NULL REFERENCES households(id)
);

CREATE TABLE recipe_ingredient (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id INT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    product_id INT NOT NULL REFERENCES products(id),
    amount TEXT NOT NULL DEFAULT ''
);

CREATE TABLE todos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task TEXT NOT NULL,
    due TIMESTAMPTZ,
    repeat TEXT,
    frequency INT,
    next_id INT REFERENCES todos(id),
    household_id INT NOT NULL REFERENCES households(id),
    completed_at TIMESTAMPTZ
);

CREATE TABLE restaurants (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    cuisine TEXT NOT NULL,
    notes TEXT NOT NULL,
    household_id INT NOT NULL REFERENCES households(id)
);


-- Drop triggers if rerunning
DROP TRIGGER IF EXISTS groceries_bump ON groceries;
DROP TRIGGER IF EXISTS grocery_lists_bump ON grocery_lists;
DROP TRIGGER IF EXISTS todos_bump ON todos;
DROP TRIGGER IF EXISTS members_bump ON household_members;
DROP TRIGGER IF EXISTS recipes_bump ON recipes;
DROP TRIGGER IF EXISTS restaurants_bump ON restaurants;
DROP TRIGGER IF EXISTS invites_bump ON invites;
DROP TRIGGER IF EXISTS households_code_bump ON households;
DROP TRIGGER IF EXISTS household_product_category_bump ON household_product_category;

-- Function
CREATE OR REPLACE FUNCTION bump_household_version()
RETURNS TRIGGER AS $$
DECLARE
    hid INT;
BEGIN
    hid := COALESCE(NEW.household_id, OLD.household_id);

    UPDATE households
    SET version = version + 1
    WHERE id = hid;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

-- Groceries have no household_id of their own; derive it from the owning list.
CREATE OR REPLACE FUNCTION bump_household_version_from_list()
RETURNS TRIGGER AS $$
DECLARE
    hid INT;
    glid INT;
BEGIN
    glid := COALESCE(NEW.grocery_list_id, OLD.grocery_list_id);

    SELECT household_id INTO hid
    FROM grocery_lists
    WHERE id = glid;

    UPDATE households
    SET version = version + 1
    WHERE id = hid;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

-- The code lives on households itself, so we can't UPDATE households from an
-- AFTER trigger here (it would recurse). Bump version inline in a BEFORE trigger
-- when the code actually changes.
CREATE OR REPLACE FUNCTION bump_household_version_on_code_change()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.code IS DISTINCT FROM NEW.code THEN
        NEW.version := OLD.version + 1;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Triggers
CREATE TRIGGER groceries_bump
AFTER INSERT OR UPDATE OR DELETE
ON groceries
FOR EACH ROW
EXECUTE FUNCTION bump_household_version_from_list();

CREATE TRIGGER grocery_lists_bump
AFTER INSERT OR UPDATE OR DELETE
ON grocery_lists
FOR EACH ROW
EXECUTE FUNCTION bump_household_version();

